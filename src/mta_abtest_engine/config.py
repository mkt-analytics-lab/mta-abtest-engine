"""Configuration: one validated source of truth for paths and parameters.

Two kinds of configuration, kept separate on purpose:

* ``Settings`` -> environment-specific values (paths, URIs, secrets).
  Read from environment variables or a local ``.env`` file. Never committed.
* ``ProjectConfig`` -> experiment/pipeline parameters (versioned in git).
  Read from ``configs/config.yaml`` and validated with Pydantic, so a typo
  fails fast with a clear error instead of silently breaking a run.
"""

from __future__ import annotations

import datetime as dt
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """Environment settings (override with env vars, e.g. ``APP_MODEL_PATH``)."""

    model_config = SettingsConfigDict(
        env_prefix="APP_", env_file=".env", extra="ignore"
    )

    config_path: Path = Path("configs/config.yaml")
    model_path: Path = Path("models/model.joblib")
    mlflow_tracking_uri: str = "sqlite:///mlflow.db"
    log_level: str = "INFO"
    # Google Cloud project that runs (and pays for) BigQuery jobs. Optional so
    # that tests and CI work without cloud access; required by warehouse code.
    gcp_project_id: str | None = None


class DataConfig(BaseModel):
    raw_path: Path
    validated_path: Path
    train_path: Path
    test_path: Path
    test_size: float = Field(gt=0, lt=1)
    n_samples: int = Field(gt=0, description="Rows generated by the example ingest")
    touchpoints_path: Path
    journeys_path: Path


class JourneyConfig(BaseModel):
    """Label horizon and temporal split (ADR 0009)."""

    horizon_days: int = Field(gt=0, le=60)
    test_start: dt.date
    data_end: dt.date = Field(description="Exclusive end of the available data")

    @model_validator(mode="after")
    def _test_period_fits_horizon(self) -> JourneyConfig:
        if self.test_start + dt.timedelta(days=self.horizon_days) >= self.data_end:
            raise ValueError("test period is shorter than the label horizon")
        return self


class ModelConfig(BaseModel):
    name: str
    params: dict[str, Any] = Field(default_factory=dict)


class EvaluationConfig(BaseModel):
    min_roc_auc: float = Field(ge=0, le=1)
    metrics_path: Path


class PropensityConfig(BaseModel):
    experiment_name: str
    report_path: Path
    bootstrap_samples: int = Field(ge=50, le=5000)
    reference_model: str = "funnel_rule"
    logistic: dict[str, Any] = Field(default_factory=dict)
    gbm: dict[str, Any] = Field(default_factory=dict)


class ParamSpec(BaseModel):
    type: Literal["int", "float"]
    low: float
    high: float
    log: bool = False

    @model_validator(mode="after")
    def _ordered(self) -> ParamSpec:
        if not self.low < self.high:
            raise ValueError("search space requires low < high")
        return self


class TuningConfig(BaseModel):
    """Optuna search for the GBM (ADR 0013)."""

    study_name: str
    storage: str
    validation_start: dt.date
    n_trials: int = Field(gt=0)
    timeout_seconds: int = Field(gt=0)
    pruning_step: int = Field(gt=0)
    fixed: dict[str, Any] = Field(default_factory=dict)
    search_space: dict[str, ParamSpec]


class TrackingConfig(BaseModel):
    experiment_name: str


class BigQueryConfig(BaseModel):
    """Warehouse parameters. Credentials come from ADC, never from config."""

    location: str = Field(
        min_length=1, description="Dataset location; must match the source data"
    )
    source_table: str = Field(min_length=1, description="GA4 export (wildcard)")
    marts_dataset: str = Field(min_length=1, description="Dataset with dbt marts")
    maximum_bytes_billed: int = Field(
        gt=0, description="Per-query cost guard: larger queries are rejected"
    )


class ProjectConfig(BaseModel):
    random_seed: int = 42
    data: DataConfig
    journey: JourneyConfig
    model: ModelConfig
    evaluation: EvaluationConfig
    propensity: PropensityConfig
    tuning: TuningConfig
    tracking: TrackingConfig

    @model_validator(mode="after")
    def _validation_fits_before_test(self) -> ProjectConfig:
        window = dt.timedelta(days=self.journey.horizon_days)
        if self.tuning.validation_start + window >= self.journey.test_start:
            raise ValueError("tuning validation period shorter than the horizon")
        return self

    bigquery: BigQueryConfig


def load_config(path: str | Path | None = None) -> ProjectConfig:
    """Load and validate the YAML pipeline configuration."""
    config_path = Path(path) if path else get_settings().config_path
    with config_path.open(encoding="utf-8") as fh:
        raw = yaml.safe_load(fh)
    return ProjectConfig.model_validate(raw)


@lru_cache
def get_settings() -> Settings:
    return Settings()
